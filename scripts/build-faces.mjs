/**
 * Builds the borrower face assets from public/borrowers/*.webp.
 * Run after adding or removing photos:  node scripts/build-faces.mjs
 *
 * Outputs
 *  - public/borrowers/generated/atlas-48.webp, atlas-128.webp: square crops packed in a grid (canvas gallery)
 *  - public/borrowers/generated/256/<n>.webp: single square crops (list rows)
 *  - app/borrowers/faces.ts: file order, names and atlas geometry
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = "public/borrowers";
const OUT = path.join(SRC, "generated");
const ATLAS_SIZES = [48, 128];
const SINGLE_SIZE = 256;
/** Photos kept in the folder but left out of the site (e.g. a strong coloured background that pulls focus). */
const EXCLUDE = new Set(["Portrait 113.webp"]);

const files = fs
  .readdirSync(SRC)
  .filter((f) => f.toLowerCase().endsWith(".webp") && !EXCLUDE.has(f))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
const cols = Math.ceil(Math.sqrt(files.length));
const rows = Math.ceil(files.length / cols);

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, String(SINGLE_SIZE)), { recursive: true });

/** Square centre crop, face assumed roughly centred. */
const square = (file, size) =>
  sharp(path.join(SRC, file)).resize(size, size, { fit: "cover", position: "centre" });

for (const size of ATLAS_SIZES) {
  const tiles = await Promise.all(files.map((f) => square(f, size).toBuffer()));
  await sharp({ create: { width: cols * size, height: rows * size, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite(tiles.map((input, i) => ({ input, left: (i % cols) * size, top: Math.floor(i / cols) * size })))
    .webp({ quality: 80 })
    .toFile(path.join(OUT, `atlas-${size}.webp`));
}

await Promise.all(
  files.map((f, i) => square(f, SINGLE_SIZE).webp({ quality: 82 }).toFile(path.join(OUT, String(SINGLE_SIZE), `${i}.webp`))),
);

// "Portrait 109.webp" has no person's name; those borrowers get a generated one.
const names = files.map((f) => {
  const name = f.replace(/\.webp$/i, "").trim();
  return /^portrait\b/i.test(name) ? null : name;
});

fs.writeFileSync(
  "app/borrowers/faces.ts",
  `// Generated by scripts/build-faces.mjs. Do not edit by hand.\n\n` +
    `export const FACE_COUNT = ${files.length};\n` +
    `export const ATLAS_COLS = ${cols};\n` +
    `export const ATLAS_SIZES = ${JSON.stringify(ATLAS_SIZES)} as const;\n` +
    `export const FACE_DIR = "/borrowers/generated";\n` +
    `export const SINGLE_SIZE = ${SINGLE_SIZE};\n\n` +
    `/** Name for each face, in atlas order. null = no name on file. */\n` +
    `export const FACE_NAMES: (string | null)[] = ${JSON.stringify(names, null, 2)};\n`,
);

console.log(`${files.length} faces, atlas ${cols}x${rows}`);
